-- Q30: Select customer name, order date, total amount, and the percentage growth in order amount from their previous order.
WITH OrderLag AS (
    SELECT id AS order_id, customer_id, order_date, total_amount,
           LAG(total_amount, 1) OVER (PARTITION BY customer_id ORDER BY order_date ASC) AS prev_amount
    FROM orders
)
SELECT o.order_id, c.first_name || ' ' || c.last_name AS customer_name, o.order_date, o.total_amount, o.prev_amount,

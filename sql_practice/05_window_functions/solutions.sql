-- Q61: Select employee name, department, hire date, and the days elapsed since the previous hire in the same department.
-- Note: SQLite does not have direct DATEDIFF. We can cast date string to julianday to get difference in days.
WITH HiredLag AS (
    SELECT first_name, last_name, department_id, hire_date,
           LAG(hire_date, 1) OVER (PARTITION BY department_id ORDER BY hire_date ASC) AS prev_hire
    FROM employees
)
SELECT first_name, last_name, department_id, hire_date, prev_hire,
       CASE 
           WHEN prev_hire IS NULL THEN NULL 
           ELSE CAST(julianday(hire_date) - julianday(prev_hire) AS INT) 
       END AS days_elapsed
FROM HiredLag;


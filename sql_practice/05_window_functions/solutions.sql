SELECT id AS order_id, order_date, total_amount,
       MAX(total_amount) OVER (ORDER BY order_date ASC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS running_max_amount
FROM orders;

-- Q89: Select employee name, salary, and the running minimum salary in their department.
SELECT first_name || ' ' || last_name AS employee_name, salary, department_id,
       MIN(salary) OVER (PARTITION BY department_id ORDER BY hire_date ASC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS running_min_dept_salary
FROM employees;

-- Q90: Select customer name, country, and the running maximum order total placed by them.
SELECT o.id AS order_id, c.first_name || ' ' || c.last_name AS customer_name, c.country, o.total_amount,
       MAX(o.total_amount) OVER (PARTITION BY o.customer_id ORDER BY o.order_date ASC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS running_max_order_amount
FROM orders o
INNER JOIN customers c ON o.customer_id = c.id;

-- Q91: Find the employee who was hired second in each department.
WITH HiredSequence AS (
    SELECT *, ROW_NUMBER() OVER (PARTITION BY department_id ORDER BY hire_date ASC) AS row_num
    FROM employees
)
SELECT * FROM HiredSequence WHERE row_num = 2;


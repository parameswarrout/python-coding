-- Q1: Assign a unique sequential integer starting from 1 to each employee sorted by salary descending (use ROW_NUMBER()).
SELECT first_name, last_name, salary,
       ROW_NUMBER() OVER (ORDER BY salary DESC) AS row_num
FROM employees;

-- Q2: Rank all employees by salary from highest to lowest. If salaries match, assign the same rank and skip ranks (use RANK()).
SELECT first_name, last_name, salary,
       RANK() OVER (ORDER BY salary DESC) AS rnk
FROM employees;

-- Q3: Rank all employees by salary from highest to lowest. If salaries match, assign same rank without skipping (use DENSE_RANK()).
SELECT first_name, last_name, salary,
       DENSE_RANK() OVER (ORDER BY salary DESC) AS dense_rnk
FROM employees;

-- Q4: Rank products by price descending within each category using ROW_NUMBER().
SELECT name, category, price,
       ROW_NUMBER() OVER (PARTITION BY category ORDER BY price DESC) AS category_row_num
FROM products;

-- Q5: Rank products by price descending within each category using DENSE_RANK().
SELECT name, category, price,
       DENSE_RANK() OVER (PARTITION BY category ORDER BY price DESC) AS category_dense_rank

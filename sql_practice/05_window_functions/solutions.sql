-- Q95: Find the product category with the second highest total sales.
WITH CategorySales AS (
    SELECT p.category, SUM(oi.quantity * oi.unit_price) AS sales,
           RANK() OVER (ORDER BY SUM(oi.quantity * oi.unit_price) DESC) AS rank
    FROM order_items oi
    INNER JOIN products p ON oi.product_id = p.id
    GROUP BY p.category
)
SELECT * FROM CategorySales WHERE rank = 2;

-- Q96: Find the department with the second lowest total salary expense.
WITH DeptSalary AS (
    SELECT department_id, SUM(salary) AS salaries,
           RANK() OVER (ORDER BY SUM(salary) ASC) AS rank
    FROM employees
    GROUP BY department_id
)
SELECT ds.department_id, d.name, ds.salaries
FROM DeptSalary ds
INNER JOIN departments d ON ds.department_id = d.id
WHERE ds.rank = 2;

-- Q97: Find the location with the second highest number of employees.
WITH LocationCount AS (
    SELECT d.location, COUNT(e.id) AS employees_count,
           RANK() OVER (ORDER BY COUNT(e.id) DESC) AS rank
    FROM employees e
    INNER JOIN departments d ON e.department_id = d.id
    GROUP BY d.location
)
SELECT * FROM LocationCount WHERE rank = 2;

-- Q98: Find the manager who has the second highest number of direct reports.
WITH ManagerReports AS (
    SELECT manager_id, COUNT(*) AS reports,
           RANK() OVER (ORDER BY COUNT(*) DESC) AS rank
    FROM employees
    WHERE manager_id IS NOT NULL
    GROUP BY manager_id
)
SELECT mr.manager_id, e.first_name, e.last_name, mr.reports
FROM ManagerReports mr
INNER JOIN employees e ON mr.manager_id = e.id
WHERE mr.rank = 2;

-- Q99: Find the product category with the second lowest stock level.
WITH CategoryStock AS (
    SELECT category, SUM(stock) AS stock_sum,
           RANK() OVER (ORDER BY SUM(stock) ASC) AS rank
    FROM products
    GROUP BY category
)
SELECT * FROM CategoryStock WHERE rank = 2;

-- Q100: Find the customer country with the second highest average order total.
WITH CountryOrders AS (
    SELECT c.country, AVG(o.total_amount) AS avg_amount,
           RANK() OVER (ORDER BY AVG(o.total_amount) DESC) AS rank
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.id
    GROUP BY c.country
)
SELECT * FROM CountryOrders WHERE rank = 2;
